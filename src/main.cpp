namespace {

const char kTrailer[8] = {'M', 'O', 'S', 'S', 'B', 'C', '0', '1'};

void usage(const char* argv0) {
  std::printf(
      "moss - the Moss capability language\n"
      "\n"
      "usage:\n"
      "  %s <file.ms> [args...]        compile and run\n"
      "  %s run <file.mbc> [args...]   run a bytecode file\n"
      "  %s -c <file.ms> [-o out.mbc]  compile to a bytecode file\n"
      "  %s build <file.ms> [-o out.exe]\n"
      "                                compile to a native executable (needs gcc)\n"
      "  %s pack <file.ms> [-o out.exe]\n"
      "                                package the embedded-VM executable\n"
      "\n"
      "options:\n"
      "  --emit-c        write <out>.c and stop (no C compiler needed)\n"
      "  --dump-tokens   print the token stream\n"
      "  --dump-ast      print the parsed AST\n"
      "  --dump-bc       print the generated bytecode\n"
      "  --no-run        compile only; do not execute\n"
      "  -h, --help      show this message\n"
      "\n"
      "environment:\n"
      "  MOSS_CC         C compiler used by 'build' (default: gcc)\n",
      argv0, argv0, argv0, argv0, argv0);
}

std::string readFile(const std::string& path) {
  std::ifstream in(path, std::ios::binary);
  if (!in) throw std::runtime_error("cannot open '" + path + "'");
  std::ostringstream ss;
  ss << in.rdbuf();
  return ss.str();
}

void writeFile(const std::string& path, const std::string& data) {
  std::ofstream out(path, std::ios::binary);
  if (!out) throw std::runtime_error("cannot write '" + path + "'");
  out.write(data.data(), (std::streamsize)data.size());
}

std::string replaceExt(const std::string& path, const std::string& ext) {
  fs::path p(path);
  p.replace_extension(ext);
  return p.string();
}

struct Options {
  std::string cmd;  // "", "run", "build", "pack", "compile"
  std::string file;
  std::string out;
  std::vector<std::string> progArgs;
  bool dumpToks = false, dumpAst = false, dumpBc = false, noRun = false;
  bool emitC = false;
};

Options parseArgs(int argc, char** argv) {
  Options o;
  for (int i = 1; i < argc; ++i) {
    std::string a = argv[i];
    if (a == "-h" || a == "--help") {
      usage(argv[0]);
      std::exit(0);
    } else if (a == "--dump-tokens") o.dumpToks = true;
    else if (a == "--dump-ast") o.dumpAst = true;
    else if (a == "--dump-bc") o.dumpBc = true;
    else if (a == "--no-run") o.noRun = true;
    else if (a == "--emit-c") o.emitC = true;
    else if (a == "-c") o.cmd = "compile";
    else if (a == "-o") {
      if (i + 1 >= argc) throw std::runtime_error("'-o' needs a file name");
      o.out = argv[++i];
    } else if (o.file.empty() && o.cmd.empty() &&
               (a == "run" || a == "build" || a == "pack")) {
      o.cmd = a;
    } else if (!o.file.empty()) {
      o.progArgs.push_back(a);
    } else if (!a.empty() && a[0] == '-') {
      throw std::runtime_error("unknown option '" + a + "'");
    } else {
      o.file = a;
    }
  }
  if (o.file.empty()) {
    usage(argv[0]);
    std::exit(2);
  }
  return o;
}

LoadedProgram compileToProgram(const std::string& file, const Options& opt,
                               const std::string& exeDir) {
  std::string src = readFile(file);

  std::vector<Token> toks = lex(src);
  if (opt.dumpToks) {
    std::printf("== tokens ==\n");
    dumpTokens(toks);
  }

  FileAst ast = parseMainFile(toks);
  if (opt.dumpAst) {
    std::printf("== ast ==\n");
    for (const auto& f : ast.functions) dumpFunc(*f);
  }

  fs::path srcPath = fs::absolute(file);
  LoadedProgram prog = loadProgram(std::move(ast),
                                   srcPath.parent_path().string(), exeDir);
  typeCheck(prog);
  return prog;
}

std::string joinArgs(const std::vector<std::string>& args) {
  std::string joined;
  for (size_t i = 0; i < args.size(); ++i) {
    if (i) joined += " ";
    joined += args[i];
  }
  return joined;
}

int runProgram(const BytecodeProgram& bc, const std::vector<std::string>& args) {
  VM vm(bc, joinArgs(args));
  return vm.run();
}

// Appends the bytecode to a copy of mossrt.exe and writes the result.
void packageExecutable(const BytecodeProgram& bc, const std::string& exeDir,
                       const std::string& outPath) {
  std::string runner = (fs::path(exeDir) / "mossrt.exe").string();
  if (!fs::exists(runner))
    throw std::runtime_error(
        "standalone runtime 'mossrt.exe' not found next to moss");

  std::string image = readFile(runner);
  std::string payload = serializeProgram(bc);

  std::string out = std::move(image);
  out += payload;

  uint64_t len = payload.size();
  char lenBytes[8];
  for (int i = 0; i < 8; ++i) lenBytes[i] = (char)((len >> (8 * i)) & 0xff);
  out.append(lenBytes, 8);
  out.append(kTrailer, 8);

  writeFile(outPath, out);
#ifndef _WIN32
  // A packaged program is an executable; writeFile only sets read/write bits.
  std::error_code ec;
  fs::permissions(outPath,
                  fs::perms::owner_exec | fs::perms::group_exec |
                      fs::perms::others_exec,
                  fs::perm_options::add, ec);
#endif
}

std::string findCompiler() {
  const char* env = std::getenv("MOSS_CC");
  if (env && *env) return env;
  return "gcc";
}

// Emits C, then runs the system C compiler on it.
void buildNative(const LoadedProgram& prog, const std::string& outPath,
                 bool emitOnly) {
  std::string cSource = emitC(prog);
  std::string cFile = emitOnly ? outPath : replaceExt(outPath, ".c");

  writeFile(cFile, cSource);
  if (emitOnly) {
    std::printf("wrote %s\n", cFile.c_str());
    return;
  }

  std::string cc = findCompiler();
#ifdef _WIN32
  // If MOSS_CC is a full path, the compiler's helper processes (cc1, cc1plus,
  // as) still need the DLLs that sit next to it, so put that directory on
  // PATH for the child.
  fs::path ccPath(cc);
  if (ccPath.has_parent_path()) {
    const char* oldPath = std::getenv("PATH");
    std::string newPath = ccPath.parent_path().string() + ";" +
                          (oldPath ? oldPath : "");
    _putenv_s("PATH", newPath.c_str());
  }
#endif
  std::string cmd = "\"" + cc + "\" -std=c11 -O2 -o \"" + outPath + "\" \"" +
                    cFile + "\"";
#ifdef _WIN32
  // cmd.exe strips the first quote of a command line that starts with one;
  // wrapping the whole thing in another pair preserves the inner quoting.
  cmd = "\"" + cmd + "\"";
#endif
  int rc = std::system(cmd.c_str());
  if (rc != 0)
    throw std::runtime_error(
        "C compiler failed; set MOSS_CC to a working gcc. "
        "The generated C is at " +
        cFile);

  std::error_code ec;
  fs::remove(cFile, ec);
  std::printf("wrote %s\n", outPath.c_str());
}

}  // namespace

int main(int argc, char** argv) {
  setvbuf(stderr, nullptr, _IONBF, 0);

  try {
    Options opt = parseArgs(argc, argv);

    fs::path exePath = fs::absolute(argv[0]);
    std::string exeDir = exePath.parent_path().string();

    if (opt.cmd == "run") {
      BytecodeProgram bc = deserializeProgram(readFile(opt.file));
      return runProgram(bc, opt.progArgs);
    }

    LoadedProgram prog = compileToProgram(opt.file, opt, exeDir);

    if (opt.cmd == "build") {
      std::string defaultOut = opt.emitC ? replaceExt(opt.file, ".c")
                                         : replaceExt(opt.file, ".exe");
      buildNative(prog, opt.out.empty() ? defaultOut : opt.out, opt.emitC);
      return 0;
    }

    // Everything below needs bytecode.
    BytecodeProgram bc = generate(prog);
    if (opt.dumpBc) {
      std::printf("== bytecode ==\n");
      disassemble(bc, std::cout);
    }

    if (opt.cmd == "compile") {
      std::string out = opt.out.empty() ? replaceExt(opt.file, ".mbc") : opt.out;
      writeFile(out, serializeProgram(bc));
      std::printf("wrote %s\n", out.c_str());
      return 0;
    }

    if (opt.cmd == "pack") {
      std::string out = opt.out.empty() ? replaceExt(opt.file, ".exe") : opt.out;
      packageExecutable(bc, exeDir, out);
      std::printf("wrote %s\n", out.c_str());
      return 0;
    }

    if (opt.noRun) return 0;
    return runProgram(bc, opt.progArgs);
  } catch (const std::exception& e) {
    std::fprintf(stderr, "moss: error: %s\n", e.what());
    return 1;
  }
}
